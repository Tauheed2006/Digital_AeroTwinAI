from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer

def create_report(mission, scenario, generated, severity,
                  telemetry, health, rul,
                  fault, component, confidence):

    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()
    elements = []

    title = Paragraph(
        "<font size=24 color='#1E40AF'><b>AeroTwin AI</b></font>",
        styles["Title"]
    )

    sub = Paragraph(
        "<b>Digital Twin Mission Health Report</b>",
        styles["Heading2"]
    )

    elements.extend([title, sub, Spacer(1, 0.25*inch)])

    info = [
        ["Mission", mission],
        ["Scenario", scenario],
        ["Generated", generated],
        ["Severity", severity]
    ]

    t = Table(info, colWidths=[1.8*inch,4*inch])
    t.setStyle(TableStyle([
        ("GRID",(0,0),(-1,-1),0.5,colors.grey),
        ("BACKGROUND",(0,0),(0,-1),colors.HexColor("#DCE3EF")),
        ("BACKGROUND",(1,3),(1,3),colors.green),
        ("TEXTCOLOR",(1,3),(1,3),colors.white),
        ("FONTNAME",(0,0),(-1,-1),"Helvetica-Bold"),
        ("BOTTOMPADDING",(0,0),(-1,-1),8),
    ]))
    elements.append(t)
    elements.append(Spacer(1,0.25*inch))

    params = [
        ["Parameter","Value"],
        ["RPM", str(round(telemetry["rpm"]))],
        ["CHT", f'{telemetry["cht"]:.1f} °C'],
        ["Oil Pressure", f'{telemetry["oil_pressure"]:.1f} bar'],
        ["Vibration", f'{telemetry["vibration"]:.2f} mm/s'],
        ["Health", f"{health}%"],
        ["RUL", f"{rul} hrs"]
    ]

    p = Table(params,colWidths=[3.3*inch,2.5*inch])
    p.setStyle(TableStyle([
        ("GRID",(0,0),(-1,-1),0.5,colors.grey),
        ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#1E40AF")),
        ("TEXTCOLOR",(0,0),(-1,0),colors.white),
        ("FONTNAME",(0,0),(-1,0),"Helvetica-Bold"),
        ("BOTTOMPADDING",(0,0),(-1,0),8),
    ]))
    elements.append(p)
    elements.append(Spacer(1,0.25*inch))

    diag = [
        ["Detected Fault", fault],
        ["Affected Component", component],
        ["Confidence", f"{confidence}%"],
        ["Severity", severity]
    ]

    d = Table(diag,colWidths=[2.8*inch,3*inch])
    d.setStyle(TableStyle([
        ("GRID",(0,0),(-1,-1),0.5,colors.grey),
        ("FONTNAME",(0,0),(-1,-1),"Helvetica-Bold"),
    ]))
    elements.append(d)
    elements.append(Spacer(1,0.3*inch))

    elements.append(Paragraph("<b>Maintenance Recommendation</b>", styles["Heading2"]))

    if health >= 90:
        rec = [
            "Continue normal operation.",
            "Inspect Healthy.",
            "Review vibration and oil telemetry.",
            "Validate repair using Mission Replay."
        ]
    elif health >= 70:
        rec = [
            "Schedule preventive maintenance.",
            "Inspect affected subsystem.",
            "Review engine temperature trends.",
            "Perform vibration analysis."
        ]
    else:
        rec = [
            "Ground aircraft immediately.",
            "Replace damaged component.",
            "Run complete AI diagnostic.",
            "Validate repair using Mission Replay."
        ]

    for r in rec:
        elements.append(Paragraph("• "+r, styles["BodyText"]))

    elements.append(Spacer(1,0.25*inch))
    elements.append(Paragraph(
        "<font size=9 color=grey>Generated by AeroTwin AI</font>",
        styles["Normal"]
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer